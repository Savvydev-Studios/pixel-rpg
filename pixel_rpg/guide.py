"""The guide book: how to play, with nothing the story has not told you.

Deliberately spoiler-free. It names no warden, no ending, and nothing about
what the Door actually is. Mechanics only - the codex is where the story
lives, and it has to be earned.

**It goes stale silently, and it had.** Rebuilt on 2026-08-31 after Savvydev
asked - *"also, probably update the guide"* - and the audit that prompted
it found the guide describing a game from several weeks earlier: four
attributes when there are nine, three save slots when there are six,
modifiers that "give something back" when they no longer do, and not one
word about the map key, the towers, the stepstones, the errands, the
favours, the skill loadout or co-op.

**This is the file rule 1d exists for.** Every one of those was a feature
that landed with tests, a section in the handoff, and nobody asking
whether the page that teaches the game needed a line.
"""
from __future__ import annotations

from dataclasses import dataclass


#: The actions a page names by their key, as `{action}` in its text.
#: `{walk}` is the four walking keys together.
NAMED_KEYS = ("interact", "sprint", "map", "hero", "quests", "trade", "save")


def key_words(binds):
    """What the guide calls each key: **yours, not the defaults** (s96).

    It said "E", "M", "(C)", "J", "T" and "F5" in so many words, so
    anyone who rebound a key was taught the wrong one by the page that
    exists to teach it. The labels are the Controls screen's own.
    """
    words = {action: binds.label_for(action) for action in NAMED_KEYS}
    walk = [binds.label_for(a) for a in ("up", "left", "down", "right")]
    words["walk"] = ("".join(walk) if all(len(w) == 1 for w in walk)
                     else " / ".join(walk))
    return words


def with_keys(line, binds):
    """One line of a page with its keys filled in."""
    return line.format_map(key_words(binds)) if "{" in line else line


